    /**
     * 맵/GEO가 바뀌었을 때 관리용 강제 재생성.
     * 평소 서버 시작에서는 prepare()만 사용.
     */
    public static void rebuildAll() {

        final PathNodeWorld world =
                PathNodeWorld.getInstance();

        for (int i = 0; i < MAP_IDS.length; i++) {
            world.rebuild(MAP_IDS[i]);
        }
    }

    /**
     * 이미 생성된 .pnode만 메모리에 올린다.
     * 파일이 없는 맵은 건드리지 않는다.
     */
    public static void preloadAll() {

        final PathNodeWorld world =
                PathNodeWorld.getInstance();

        for (int i = 0; i < MAP_IDS.length; i++) {

            final int mapId =
                    MAP_IDS[i];

            if (new File(
                    CACHE_DIR,
                    mapId + ".pnode")
                    .isFile()) {

                world.preload(mapId);
            }
        }
    }
