	public static void clickItem(L1PcInstance pc, int itemId, L1ItemInstance l1iteminstance) {

		switch (itemId) {
		case 3000366:// 신규 영입
			if (pc.getInventory().checkItem(3000366, 1)) { // 체크 되는 아이템과 수량
				pc.getInventory().consumeItem(3000366, 1); // 삭제되는 아이템과 수량qrltrue);
				if (pc.isWarrior()) {
                    grantWarrior(pc);
                }
				if (pc.isKnight()) {
                    grantKnight(pc);
                }
				if (pc.isDragonknight()) {
                    grantDragonknight(pc);
                }
				if (pc.isCrown()) {
                    grantCrown(pc);
                }
				if (pc.isWizard()) {
                    grantWizard(pc);
                }
				if (pc.isBlackwizard()) {
                    grantBlackwizard(pc);
                }
				if (pc.isElf()) {
                    grantElf(pc);
                }
				if (pc.isDarkelf()) {
                    grantDarkelf(pc);
                }
			}
			break;
		}
	}




